const ACCENTS: Record<string, string> = { Á: "A", É: "E", Í: "I", Ó: "O", Ú: "U", Ñ: "N", Ü: "U", º: "O" };

/** Dibuja texto sobre un buffer RGBA (con sombra para legibilidad). */
export function drawText(
  buf: Uint8ClampedArray,
  width: number,
  height: number,
  text: string,
  x0: number,
  y0: number,
  scale = 2,
  color: [number, number, number] = [235, 245, 255],
) {
  const upper = text.toUpperCase();
  for (const [dx, dy, col] of [
    [1, 1, [0, 0, 0] as [number, number, number]],
    [0, 0, color],
  ] as const) {
    let x = x0 + dx;
    for (const raw of upper) {
      const ch = ACCENTS[raw] ?? raw;
      const glyph = GLYPHS[ch] ?? GLYPHS[" "]!;
      for (let row = 0; row < 7; row++) {
        for (let colIdx = 0; colIdx < 5; colIdx++) {
          if (!((glyph[row]! >> (4 - colIdx)) & 1)) continue;
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const px = x + colIdx * scale + sx;
              const py = y0 + dy + row * scale + sy;
              if (px < 0 || py < 0 || px >= width || py >= height) continue;
              const i = (py * width + px) * 4;
              buf[i] = col[0];
              buf[i + 1] = col[1];
              buf[i + 2] = col[2];
            }
          }
        }
      }
      x += 6 * scale;
    }
  }
}
